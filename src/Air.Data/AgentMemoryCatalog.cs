namespace Platform.Data;

public static class AgentMemoryCatalog
{
  public static AppAgentMemory[] DefaultRows() =>
  [
    new()
    {
      Kind = AgentMemoryKinds.Rule,
      Title = "Receipt & Invoice Line Extraction",
      Content = "When reading attached receipt or invoice photos, extract every individual line item with its exact product/service name, quantity, unit price, and line total, and assign the most matching category from the available dictionaries.",
      Priority = 200,
      IsPinned = true,
      IsActive = true
    },
    new()
    {
      Kind = AgentMemoryKinds.Rule,
      Title = "Proposal Confirmation Policy",
      Content = "Never mutate database records without user confirmation. Always emit <air_proposal> cards so the user can review fields, line items, and any duplicate receipt warnings before confirming.",
      Priority = 190,
      IsPinned = true,
      IsActive = true
    },
    new()
    {
      Kind = AgentMemoryKinds.Rule,
      Title = "Counterparty & Dictionary Resolution",
      Content = "Match counterparties, categories, accounts, and warehouses by their existing dictionary IDs whenever possible. Only propose creating a new counterparty or dictionary item when no matching entry exists.",
      Priority = 180,
      IsPinned = true,
      IsActive = true
    },
    new()
    {
      Kind = AgentMemoryKinds.Preference,
      Title = "Concise Analytical Formatting",
      Content = "Keep chat explanations concise (1-3 sentences) when presenting proposals, and use structured Markdown tables, <air_kpi>, and <air_chart> blocks when answering analytical or reporting questions.",
      Priority = 100,
      IsPinned = false,
      IsActive = true
    }
  ];

  public static async Task EnsureSeededAsync(
    PlatformDbContext db,
    string? seedDomainKnowledge = null,
    CancellationToken ct = default)
  {
    try
    {
      if (db.Database.IsRelational())
      {
        await db.Database.ExecuteSqlRawAsync(
          """
          CREATE TABLE IF NOT EXISTS "AppAgentMemory" (
            "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "TenantId" bigint NULL,
            "Kind" character varying(64) NOT NULL DEFAULT 'Rule',
            "Module" character varying(64) NULL,
            "Title" character varying(200) NOT NULL DEFAULT '',
            "Content" character varying(4000) NOT NULL DEFAULT '',
            "Priority" integer NOT NULL DEFAULT 100,
            "IsPinned" boolean NOT NULL DEFAULT false,
            "IsActive" boolean NOT NULL DEFAULT true,
            "HitCount" integer NOT NULL DEFAULT 0,
            "LastUsedAt" timestamp with time zone NULL,
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT now(),
            "UpdatedAt" timestamp with time zone NULL,
            "Ver" integer NOT NULL DEFAULT 1
          );
          """,
          ct);
      }
    }
    catch
    {
      // Ignore if provider uses different DDL syntax or table already exists
    }

    List<AppAgentMemory> existing;
    try
    {
      existing = await db.AppAgentMemory.IgnoreQueryFilters().ToListAsync(ct);
    }
    catch
    {
      return;
    }

    var changed = false;
    foreach (var seed in DefaultRows())
    {
      if (!existing.Any(e => string.Equals(e.Title, seed.Title, StringComparison.OrdinalIgnoreCase)))
      {
        db.AppAgentMemory.Add(seed);
        existing.Add(seed);
        changed = true;
      }
    }

    if (!string.IsNullOrWhiteSpace(seedDomainKnowledge) &&
        !existing.Any(e => e.Kind == AgentMemoryKinds.Seed))
    {
      var trimmed = seedDomainKnowledge.Trim();
      if (trimmed.Length > 3800)
      {
        trimmed = trimmed[..3800];
      }

      db.AppAgentMemory.Add(new AppAgentMemory
      {
        Kind = AgentMemoryKinds.Seed,
        Title = "Application Domain Knowledge & Workflows",
        Content = trimmed,
        Priority = 150,
        IsPinned = true,
        IsActive = true
      });
      changed = true;
    }

    if (changed)
    {
      await db.SaveChangesAsync(ct);
    }
  }
}
