namespace Platform.App.TypeScript;

public static class ContractExporter
{
  public static string GenerateContracts(params Assembly[] assemblies)
  {
    var allAssemblies = assemblies
      .Append(typeof(ContractExporter).Assembly)
      .Append(typeof(MutationOutcome).Assembly)
      .Append(typeof(UiContractAttribute).Assembly)
      .Distinct()
      .ToArray();

    var exportedTypes = allAssemblies
      .SelectMany(static a =>
      {
        try
        {
          return a.GetExportedTypes();
        }
        catch (NotSupportedException)
        {
          return a.GetTypes().Where(static t => t.IsPublic || t.IsNestedPublic);
        }
        catch
        {
          return [];
        }
      })
      .Distinct()
      .ToList();

    var baseSlotTypes = new HashSet<Type>
    {
      typeof(PanelModel),
      typeof(CellModel),
      typeof(HeaderModel),
      typeof(FormElementModel),
      typeof(NavElementModel)
    };

    var registeredNames = new Dictionary<string, Type>(StringComparer.Ordinal);
    var knownNames = new HashSet<string>(StringComparer.Ordinal)
    {
      "PanelKinds",
      "PanelModel",
      "CellKinds",
      "CellModel",
      "HeaderKinds",
      "HeaderModel",
      "FormElementKinds",
      "FormElementModel",
      "NavElementKinds",
      "NavElementModel",
      "PlatformKind",
      "Page",
      "GridPageDto"
    };

    var vocabularyTypes = exportedTypes
      .Where(static t => t.IsClass && t.IsAbstract && t.IsSealed && !t.IsGenericTypeDefinition &&
                         t.GetCustomAttribute<UiContractAttribute>() != null)
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    foreach (var vocab in vocabularyTypes)
    {
      RegisterContractName(registeredNames, knownNames, vocab.Name, vocab);
    }

    var enumTypes = exportedTypes
      .Where(static t => t.IsEnum && t.GetCustomAttribute<UiContractAttribute>() != null)
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    foreach (var enumType in enumTypes)
    {
      RegisterContractName(registeredNames, knownNames, enumType.Name, enumType);
    }

    var polymorphicUnionTypes = exportedTypes
      .Where(t => t.IsClass && t.IsAbstract && !t.IsSealed && !t.IsGenericTypeDefinition &&
                  !baseSlotTypes.Contains(t) &&
                  t.GetCustomAttribute<UiContractAttribute>() != null &&
                  t.GetCustomAttributes<JsonDerivedTypeAttribute>().Any())
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    foreach (var unionType in polymorphicUnionTypes)
    {
      RegisterContractName(registeredNames, knownNames, unionType.Name, unionType);
    }

    var interfaceTypes = exportedTypes
      .Where(static t => (t.IsClass && !(t.IsAbstract && t.IsSealed) || t.IsValueType && !t.IsEnum && !t.IsPrimitive) &&
                         !t.IsGenericTypeDefinition)
      .Where(t => !baseSlotTypes.Contains(t))
      .Where(static t => !(t.IsAbstract && t.GetCustomAttributes<JsonDerivedTypeAttribute>().Any()))
      .Where(static t => t.GetCustomAttribute<UiContractAttribute>() != null ||
                         !t.IsAbstract && typeof(IUiSlotModel).IsAssignableFrom(t))
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    var interfaceTypeSet = interfaceTypes.ToHashSet();
    foreach (var iface in interfaceTypes)
    {
      RegisterContractName(registeredNames, knownNames, iface.Name, iface);
    }

    var sb = new StringBuilder();
    sb.AppendLine("// Auto-generated by Platform ContractExporter. Do NOT edit manually.");
    sb.AppendLine();

    // 1. Export Vocabularies, Enums, Polymorphic Unions & Endpoint Utility Types
    ExportVocabularies(sb, vocabularyTypes, enumTypes, polymorphicUnionTypes, knownNames);

    // 2. Export Slot Kind Interfaces & PlatformKind
    ExportSlotInterfaces(sb, interfaceTypes);

    // 3. Export Interfaces
    foreach (var type in interfaceTypes)
    {
      ExportInterface(sb, type, interfaceTypeSet, knownNames);
    }

    return sb.ToString();
  }

  private static void RegisterContractName(
    Dictionary<string, Type> registeredNames,
    HashSet<string> knownNames,
    string tsName,
    Type type)
  {
    if (registeredNames.TryGetValue(tsName, out var existing) && existing != type)
    {
      throw new InvalidOperationException(
        $"Duplicate TypeScript contract name '{tsName}' declared by '{existing.FullName}' and '{type.FullName}'.");
    }

    if (knownNames.Contains(tsName) && !registeredNames.ContainsKey(tsName))
    {
      throw new InvalidOperationException(
        $"TypeScript contract name '{tsName}' on '{type.FullName}' collides with a reserved platform contract type.");
    }

    registeredNames[tsName] = type;
    knownNames.Add(tsName);
  }

