  private static void ExportUnionFromConsts(StringBuilder sb, Type type, string name)
  {
    var values = type.GetFields(BindingFlags.Public | BindingFlags.Static | BindingFlags.FlattenHierarchy)
      .Where(f => f.IsLiteral && !f.IsInitOnly && f.FieldType == typeof(string))
      .Select(f => $"'{f.GetRawConstantValue()}'");

    sb.AppendLine($"export type {name} = {string.Join(" | ", values)};");
    sb.AppendLine();
  }

  private static void ExportInterface(StringBuilder sb, Type type)
  {
    var name = type.Name;
    var extendsClause = type.BaseType is { } bt &&
                        (bt == typeof(GridRequest) || bt == typeof(FormRequest) || bt == typeof(MutationResultDto))
      ? $" extends {bt.Name}"
      : string.Empty;
    sb.AppendLine($"export interface {name}{extendsClause} {{");

    // If it's a polymorphic component model or FilterNode, emit its kind literal
    if (!type.IsAbstract &&
        (typeof(PanelModel).IsAssignableFrom(type) ||
         typeof(CellModel).IsAssignableFrom(type) ||
         typeof(HeaderModel).IsAssignableFrom(type) ||
         typeof(FormElementModel).IsAssignableFrom(type) ||
         typeof(NavElementModel).IsAssignableFrom(type) ||
         typeof(FilterNode).IsAssignableFrom(type)))
    {
      var kind = name.EndsWith("Model") ? name[..^5] : name;
      sb.AppendLine($"  kind: '{kind}';");
    }

    var isClientOptionalType = type.GetCustomAttribute<ClientOptionalAttribute>(inherit: true) != null;
    var nullability = new NullabilityInfoContext();
    var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance);
    foreach (var prop in properties)
    {
      var jsonIgnore = prop.GetCustomAttribute<JsonIgnoreAttribute>();
      if (jsonIgnore != null && jsonIgnore.Condition == JsonIgnoreCondition.Always)
      {
        continue;
      }

      var nullInfo = nullability.Create(prop);
      var isNullable = nullInfo.WriteState == NullabilityState.Nullable ||
                       nullInfo.ReadState == NullabilityState.Nullable ||
                       Nullable.GetUnderlyingType(prop.PropertyType) != null ||
                       jsonIgnore != null && jsonIgnore.Condition == JsonIgnoreCondition.WhenWritingNull;
      var propName = char.ToLowerInvariant(prop.Name[0]) + prop.Name[1..];
      var isOptional = isClientOptionalType ||
                       isNullable ||
                       prop.GetCustomAttribute<ClientOptionalAttribute>() != null ||
                       jsonIgnore != null && jsonIgnore.Condition == JsonIgnoreCondition.WhenWritingDefault;
      var tsType = ToTsType(prop);

      sb.AppendLine($"  {propName}{(isOptional ? "?" : "")}: {(isNullable ? $"{tsType} | null" : tsType)};");
    }

    sb.AppendLine("}");
    sb.AppendLine();
  }

