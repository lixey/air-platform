  private static void ExportSlotMap(StringBuilder sb, string interfaceName, IEnumerable<Type> unionTypes)
  {
    sb.AppendLine($"export interface {interfaceName} {{");
    foreach (var type in unionTypes.OrderBy(t => t.Name))
    {
      var kind = type.Name.EndsWith("Model") ? type.Name[..^5] : type.Name;
      sb.AppendLine($"  {kind}: {type.Name};");
    }

    sb.AppendLine("}");
    sb.AppendLine();
  }

  private static string ToTsType(PropertyInfo prop)
  {
    if (prop.DeclaringType == typeof(NavButtonModel) && prop.Name == nameof(NavButtonModel.Badge))
    {
      return "string | number";
    }

    if (prop.GetCustomAttribute<WireNumberAttribute>() != null)
    {
      return "number";
    }

    var oneOf = prop.GetCustomAttribute<OneOfAttribute>();
    if (oneOf?.Vocabularies.Count > 0)
    {
      return string.Join(" | ", oneOf.Vocabularies.Select(v => v.Name));
    }

    return MapType(prop.PropertyType);
  }

  private static string MapType(Type type)
  {
    var underlying = Nullable.GetUnderlyingType(type) ?? type;

    if (underlying == typeof(string))
    {
      return "string";
    }

    if (underlying == typeof(bool))
    {
      return "boolean";
    }

    if (underlying == typeof(int) || underlying == typeof(long) ||
        underlying == typeof(float) || underlying == typeof(double) ||
        underlying == typeof(decimal))
    {
      return "number";
    }

    if (underlying == typeof(DateTime) || underlying == typeof(DateTimeOffset) || underlying == typeof(DateOnly))
    {
      return "string";
    }

    if (underlying == typeof(object) || underlying == typeof(JsonElement))
    {
      return "unknown";
    }

    if (underlying.IsArray)
    {
      return $"{MapType(underlying.GetElementType()!)}[]";
    }

    if (underlying.IsGenericType && (underlying.GetGenericTypeDefinition() == typeof(Dictionary<,>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(IDictionary<,>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>)))
    {
      var keyType = MapType(underlying.GetGenericArguments()[0]);
      var valType = MapType(underlying.GetGenericArguments()[1]);
      return $"Record<{keyType}, {valType}>";
    }

    if (underlying.IsGenericType && (underlying.GetGenericTypeDefinition() == typeof(List<>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(IReadOnlyList<>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(IEnumerable<>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(ICollection<>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(IReadOnlyCollection<>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(HashSet<>) ||
                                     underlying.GetGenericTypeDefinition() == typeof(ISet<>)))
    {
      return $"{MapType(underlying.GetGenericArguments()[0])}[]";
    }

    return underlying.Name;
  }
