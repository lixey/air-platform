  public static string GenerateContracts(params Assembly[] assemblies)
  {
    var allAssemblies = assemblies
      .Append(typeof(ContractExporter).Assembly)
      .Append(typeof(ListRequest).Assembly)
      .Distinct()
      .ToArray();

    var sb = new StringBuilder();
    sb.AppendLine("// Auto-generated by Air.Platform ContractExporter. Do NOT edit manually.");
    sb.AppendLine();

    // 1. Export Vocabularies & Utility Types
    ExportVocabularies(sb);

    // 2. Discover UI Types
    var baseSlotTypes = new HashSet<Type>
    {
      typeof(PanelModel),
      typeof(CellModel),
      typeof(HeaderModel),
      typeof(FormElementModel),
      typeof(NavElementModel)
    };

    var types = allAssemblies
      .SelectMany(a =>
      {
        try
        {
          return a.GetExportedTypes();
        }
        catch
        {
          return [];
        }
      })
      .Where(t => t.IsClass && !(t.IsAbstract && t.IsSealed) && !t.IsGenericTypeDefinition)
      .Where(t => !baseSlotTypes.Contains(t))
      .Where(t => t.GetCustomAttribute<UiContractAttribute>() != null ||
                  !t.IsAbstract && (
                    typeof(PanelModel).IsAssignableFrom(t) ||
                    typeof(CellModel).IsAssignableFrom(t) ||
                    typeof(HeaderModel).IsAssignableFrom(t) ||
                    typeof(FormElementModel).IsAssignableFrom(t) ||
                    typeof(NavElementModel).IsAssignableFrom(t) ||
                    t == typeof(ListRequest) ||
                    t == typeof(FilterGroup) ||
                    t == typeof(FilterRule) ||
                    t == typeof(PickedValue) ||
                    t == typeof(SortRule) ||
                    t == typeof(Reference)))
      .Distinct()
      .ToList();

    // 3. Export Slot Kind Interfaces & PlatformKind
    ExportSlotInterfaces(sb, types);

    // 4. Export Interfaces
    foreach (var type in types.OrderBy(t => t.Name))
    {
      ExportInterface(sb, type);
    }

    return sb.ToString();
  }

