using Platform.Api.Host.Internals;

namespace Platform.App.TypeScript;

public static class ContractExporter
{
  public static string GenerateContracts(params Assembly[] assemblies)
  {
    var allAssemblies = assemblies
      .Append(typeof(ContractExporter).Assembly)
      .Append(typeof(MutationOutcome).Assembly)
      .Append(typeof(UiContractAttribute).Assembly)
      .Distinct()
      .ToArray();

    var exportedTypes = allAssemblies
      .SelectMany(static a =>
      {
        try
        {
          return a.GetExportedTypes();
        }
        catch (NotSupportedException)
        {
          return a.GetTypes().Where(static t => t.IsPublic || t.IsNestedPublic);
        }
        catch
        {
          return [];
        }
      })
      .Distinct()
      .ToList();

    var baseSlotTypes = new HashSet<Type>
    {
      typeof(PanelModel),
      typeof(CellModel),
      typeof(HeaderModel),
      typeof(FormElementModel),
      typeof(NavElementModel)
    };

    var registeredNames = new Dictionary<string, Type>(StringComparer.Ordinal);
    var knownNames = new HashSet<string>(StringComparer.Ordinal)
    {
      "PanelKinds",
      "PanelModel",
      "CellKinds",
      "CellModel",
      "HeaderKinds",
      "HeaderModel",
      "FormElementKinds",
      "FormElementModel",
      "NavElementKinds",
      "NavElementModel",
      "PlatformKind",
      "Page",
      "GridPageDto"
    };

    var vocabularyTypes = exportedTypes
      .Where(static t => t.IsClass && t.IsAbstract && t.IsSealed && !t.IsGenericTypeDefinition &&
                         t.GetCustomAttribute<UiContractAttribute>() != null)
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    foreach (var vocab in vocabularyTypes)
    {
      RegisterContractName(registeredNames, knownNames, vocab.Name, vocab);
    }

    var enumTypes = exportedTypes
      .Where(static t => t.IsEnum && t.GetCustomAttribute<UiContractAttribute>() != null)
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    foreach (var enumType in enumTypes)
    {
      RegisterContractName(registeredNames, knownNames, enumType.Name, enumType);
    }

    var polymorphicUnionTypes = exportedTypes
      .Where(t => t.IsClass && t.IsAbstract && !t.IsSealed && !t.IsGenericTypeDefinition &&
                  !baseSlotTypes.Contains(t) &&
                  t.GetCustomAttribute<UiContractAttribute>() != null &&
                  t.GetCustomAttributes<JsonDerivedTypeAttribute>().Any())
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    foreach (var unionType in polymorphicUnionTypes)
    {
      RegisterContractName(registeredNames, knownNames, unionType.Name, unionType);
    }

    var interfaceTypes = exportedTypes
      .Where(static t => (t.IsClass && !(t.IsAbstract && t.IsSealed) || t.IsValueType && !t.IsEnum && !t.IsPrimitive) &&
                         !t.IsGenericTypeDefinition)
      .Where(t => !baseSlotTypes.Contains(t))
      .Where(static t => !(t.IsAbstract && t.GetCustomAttributes<JsonDerivedTypeAttribute>().Any()))
      .Where(static t => t.GetCustomAttribute<UiContractAttribute>() != null ||
                         !t.IsAbstract && typeof(IUiSlotModel).IsAssignableFrom(t))
      .OrderBy(static t => t.Name, StringComparer.Ordinal)
      .ToList();

    var interfaceTypeSet = interfaceTypes.ToHashSet();
    foreach (var iface in interfaceTypes)
    {
      RegisterContractName(registeredNames, knownNames, iface.Name, iface);
    }

    var sb = new StringBuilder();
    sb.AppendLine("// Auto-generated by Platform ContractExporter. Do NOT edit manually.");
    sb.AppendLine();

    // 1. Export Vocabularies, Enums, Polymorphic Unions & Endpoint Utility Types
    ExportVocabularies(sb, vocabularyTypes, enumTypes, polymorphicUnionTypes, knownNames);
    ExportEndpointTables(sb, exportedTypes, knownNames);

    // 2. Export Slot Kind Interfaces & PlatformKind
    ExportSlotInterfaces(sb, interfaceTypes);

    // 3. Export Interfaces
    foreach (var type in interfaceTypes)
    {
      ExportInterface(sb, type, interfaceTypeSet, knownNames);
    }

    return sb.ToString();
  }

  private static void RegisterContractName(
    Dictionary<string, Type> registeredNames,
    HashSet<string> knownNames,
    string tsName,
    Type type)
  {
    if (registeredNames.TryGetValue(tsName, out var existing) && existing != type)
    {
      throw new InvalidOperationException(
        $"Duplicate TypeScript contract name '{tsName}' declared by '{existing.FullName}' and '{type.FullName}'.");
    }

    if (knownNames.Contains(tsName) && !registeredNames.ContainsKey(tsName))
    {
      throw new InvalidOperationException(
        $"TypeScript contract name '{tsName}' on '{type.FullName}' collides with a reserved platform contract type.");
    }

    registeredNames[tsName] = type;
    knownNames.Add(tsName);
  }

  private static void ExportVocabularies(
    StringBuilder sb,
    IReadOnlyList<Type> vocabularyTypes,
    IReadOnlyList<Type> enumTypes,
    IReadOnlyList<Type> polymorphicUnionTypes,
    HashSet<string> knownNames)
  {
    foreach (var vocabType in vocabularyTypes)
    {
      ExportUnionFromConsts(sb, vocabType, vocabType.Name);
    }

    foreach (var enumType in enumTypes)
    {
      ExportEnumUnion(sb, enumType);
    }

    foreach (var unionType in polymorphicUnionTypes)
    {
      var derivedNames = unionType
        .GetCustomAttributes<JsonDerivedTypeAttribute>()
        .Select(d =>
        {
          if (!knownNames.Contains(d.DerivedType.Name))
          {
            throw new InvalidOperationException(
              $"Polymorphic contract '{unionType.FullName}' references derived type '{d.DerivedType.FullName}' which is not marked with [UiContract].");
          }

          return d.DerivedType.Name;
        })
        .ToList();
      sb.AppendLine($"export type {unionType.Name} = {string.Join(" | ", derivedNames)};");
      sb.AppendLine();
    }

    sb.AppendLine("export interface Page<TRow = unknown> {");
    sb.AppendLine("  rows: TRow[];");
    sb.AppendLine("  total?: number | null;");
    sb.AppendLine("  hasMore: boolean;");
    sb.AppendLine("  page: number;");
    sb.AppendLine("  pageSize: number;");
    sb.AppendLine("}");
    sb.AppendLine();
    sb.AppendLine("export interface GridPageDto<TRow = RowDto> extends Page<TRow> {");
    sb.AppendLine("  bottomRows?: TRow[] | null;");
    sb.AppendLine("  forms?: Record<string, OverlayDto> | null;");
    sb.AppendLine("  namedFilterCounts?: Record<string, number> | null;");
    sb.AppendLine("  topRows?: TRow[] | null;");
    sb.AppendLine("}");
    sb.AppendLine();
  }

  private static void ExportEndpointTables(StringBuilder sb, List<Type> exportedTypes, HashSet<string> knownNames)
  {
    var nullability = new NullabilityInfoContext();
    ExportServiceEndpointsInterface(sb, "GridServiceEndpoints", typeof(GridService<,>), nullability, knownNames);
    ExportServiceEndpointsInterface(sb, "FileGridServiceEndpoints", typeof(FileGridService<>), nullability, knownNames);
    ExportServiceEndpointsInterface(sb, "ScreenServiceEndpoints", typeof(ScreenService), nullability, knownNames);
    ExportServiceEndpointsInterface(sb, "ReportServiceEndpoints", typeof(ReportService), nullability, knownNames);
    ExportServiceEndpointsInterface(sb, "FormServiceEndpoints", typeof(FormService<>), nullability, knownNames);

    var catalog = new ModuleCatalog();
    foreach (var serviceType in exportedTypes.Where(static t =>
               t is { IsClass: true, IsAbstract: false } && typeof(IPlatformService).IsAssignableFrom(t)))
    {
      if (serviceType.GetCustomAttribute<ServiceRouteAttribute>() is { } routeAttr)
      {
        catalog.RegisterPlatformService(routeAttr.Route, serviceType);
      }
    }

    var registry = EndpointRegistry.Build(catalog.Freeze());
    sb.AppendLine("export interface PlatformEndpoints {");
    foreach (var desc in registry.All
               .Where(static d => !d.IsDynamicAction && d.Method is not null)
               .OrderBy(static d => $"{d.ServiceName}/{d.ActionName}", StringComparer.Ordinal))
    {
      var routeKey = FormatTsPropertyKey($"{desc.ServiceName}/{desc.ActionName}");
      var reqTs = ResolveEndpointRequestTs(desc.Method!, desc.ExplicitRequestType, desc.UsesFormFiles, desc.Parameters, knownNames);
      var ansTs = ResolveEndpointAnswerTs(desc.Method!, desc.ExplicitResponseType, desc.ExplicitResponseNullable, nullability, knownNames);
      sb.AppendLine($"  {routeKey}: {{ request: {reqTs}; answer: {ansTs} }};");
    }

    sb.AppendLine("}");
    sb.AppendLine();
  }

  private static void ExportServiceEndpointsInterface(
    StringBuilder sb,
    string interfaceName,
    Type serviceType,
    NullabilityInfoContext nullability,
    HashSet<string> knownNames)
  {
    sb.AppendLine($"export interface {interfaceName} {{");
    foreach (var ep in EndpointRegistry.DescribeServiceType(serviceType)
               .OrderBy(static e => e.ActionName, StringComparer.Ordinal))
    {
      var key = FormatTsPropertyKey(ep.ActionName);
      var reqTs = ResolveEndpointRequestTs(ep.Method, ep.ExplicitRequestType, ep.UsesFormFiles, ep.Parameters, knownNames);
      var ansTs = ResolveEndpointAnswerTs(ep.Method, ep.ExplicitResponseType, ep.ExplicitResponseNullable, nullability, knownNames);
      sb.AppendLine($"  {key}: {{ request: {reqTs}; answer: {ansTs} }};");
    }

    sb.AppendLine("}");
    sb.AppendLine();
  }

  private static string FormatTsPropertyKey(string key) =>
    key.All(static c => char.IsLetterOrDigit(c) || c == '_') ? key : $"'{key}'";

  private static string ResolveEndpointRequestTs(
    MethodInfo method,
    Type? explicitRequestType,
    bool usesFormFiles,
    IReadOnlyList<EndpointParameter> parameters,
    HashSet<string> knownNames)
  {
    var context = $"Endpoint '{method.DeclaringType?.FullName}.{method.Name}' request";
    if (explicitRequestType is not null)
    {
      return MapType(explicitRequestType, context, knownNames);
    }

    if (usesFormFiles)
    {
      return "FormData";
    }

    foreach (var p in parameters)
    {
      if (EndpointRegistry.IsBodyParameterKind(p.Kind))
      {
        var mapped = MapType(p.ParameterType, context, knownNames);
        return p.IsNullable ? $"{mapped} | null" : mapped;
      }
    }

    return "void";
  }

  private static string ResolveEndpointAnswerTs(
    MethodInfo method,
    Type? explicitResponseType,
    bool explicitResponseNullable,
    NullabilityInfoContext nullability,
    HashSet<string> knownNames)
  {
    var context = $"Endpoint '{method.DeclaringType?.FullName}.{method.Name}' response";
    if (explicitResponseType is not null)
    {
      var ts = explicitResponseType == typeof(Stream)
        ? "Blob"
        : MapType(explicitResponseType, context, knownNames);
      return explicitResponseNullable ? $"{ts} | null" : ts;
    }

    var returnType = method.ReturnType;
    if (returnType == typeof(void) || returnType == typeof(Task) || returnType == typeof(ValueTask))
    {
      return nameof(MutationResultDto);
    }

    var retNullability = nullability.Create(method.ReturnParameter);
    Type unwrapped;
    bool isNullable;
    if (returnType.IsGenericType &&
        (returnType.GetGenericTypeDefinition() == typeof(Task<>) ||
         returnType.GetGenericTypeDefinition() == typeof(ValueTask<>)))
    {
      unwrapped = returnType.GetGenericArguments()[0];
      isNullable = Nullable.GetUnderlyingType(unwrapped) is not null ||
                   retNullability.GenericTypeArguments is [{ ReadState: NullabilityState.Nullable }];
    }
    else
    {
      unwrapped = returnType;
      isNullable = Nullable.GetUnderlyingType(unwrapped) is not null ||
                   retNullability.ReadState == NullabilityState.Nullable;
    }

    if (typeof(IResult).IsAssignableFrom(unwrapped))
    {
      return "unknown";
    }

    if (unwrapped == typeof(Stream))
    {
      return isNullable ? "Blob | null" : "Blob";
    }

    var mapped = MapType(unwrapped, context, knownNames);
    return isNullable ? $"{mapped} | null" : mapped;
  }

  private static void ExportUnionFromConsts(StringBuilder sb, Type type, string name)
  {
    var values = type.GetFields(BindingFlags.Public | BindingFlags.Static | BindingFlags.FlattenHierarchy)
      .Where(static f => f.IsLiteral && !f.IsInitOnly && f.FieldType == typeof(string))
      .Select(static f => $"'{f.GetRawConstantValue()}'")
      .ToList();

    if (values.Count == 0)
    {
      throw new InvalidOperationException(
        $"Vocabulary contract '{type.FullName}' is marked with [UiContract] but declares no public const string fields.");
    }

    sb.AppendLine($"export type {name} = {string.Join(" | ", values)};");
    sb.AppendLine();
  }

  private static void ExportEnumUnion(StringBuilder sb, Type enumType)
  {
    var converterType = enumType.GetCustomAttribute<JsonConverterAttribute>()?.ConverterType;
    var isStringEnum = converterType != null &&
                       (typeof(JsonStringEnumConverter).IsAssignableFrom(converterType) ||
                        converterType is { IsGenericType: true } && converterType.GetGenericTypeDefinition() == typeof(JsonStringEnumConverter<>));
    var values = isStringEnum
      ? Enum.GetNames(enumType).Select(static n => $"'{n}'").ToList()
      : Enum.GetValuesAsUnderlyingType(enumType)
        .Cast<object>()
        .Select(static v => Convert.ToString(v, CultureInfo.InvariantCulture)!)
        .Distinct(StringComparer.Ordinal)
        .ToList();

    if (values.Count == 0)
    {
      throw new InvalidOperationException(
        $"Enum contract '{enumType.FullName}' is marked with [UiContract] but declares no members.");
    }

    sb.AppendLine($"export type {enumType.Name} = {string.Join(" | ", values)};");
    sb.AppendLine();
  }

  private static void ExportInterface(
    StringBuilder sb,
    Type type,
    HashSet<Type> interfaceTypeSet,
    HashSet<string> knownNames)
  {
    var name = type.Name;
    var exportedBase = FindNearestExportedBase(type, interfaceTypeSet);
    var extendsClause = exportedBase != null ? $" extends {exportedBase.Name}" : string.Empty;
    sb.AppendLine($"export interface {name}{extendsClause} {{");

    if (!type.IsAbstract)
    {
      if (TryResolvePolymorphicDiscriminator(type, out var discProp, out var discLiteral))
      {
        sb.AppendLine($"  {discProp}: {discLiteral};");
      }
      else if (typeof(IUiSlotModel).IsAssignableFrom(type))
      {
        var kind = name.EndsWith("Model", StringComparison.Ordinal) ? name[..^5] : name;
        sb.AppendLine($"  kind: '{kind}';");
      }
    }

    var isClientOptionalType = type.GetCustomAttribute<ClientOptionalAttribute>(inherit: true) != null;
    var nullability = new NullabilityInfoContext();
    var properties = CollectPropertiesSinceExportedBase(type, exportedBase);
    foreach (var prop in properties)
    {
      var jsonIgnore = prop.GetCustomAttribute<JsonIgnoreAttribute>();
      if (jsonIgnore != null && jsonIgnore.Condition == JsonIgnoreCondition.Always)
      {
        continue;
      }

      var nullInfo = nullability.Create(prop);
      var isNullable = nullInfo.WriteState == NullabilityState.Nullable ||
                       nullInfo.ReadState == NullabilityState.Nullable ||
                       Nullable.GetUnderlyingType(prop.PropertyType) != null ||
                       jsonIgnore != null && jsonIgnore.Condition == JsonIgnoreCondition.WhenWritingNull;
      var propName = char.ToLowerInvariant(prop.Name[0]) + prop.Name[1..];
      var isOptional = isClientOptionalType ||
                       isNullable ||
                       prop.GetCustomAttribute<ClientOptionalAttribute>() != null ||
                       jsonIgnore != null && jsonIgnore.Condition == JsonIgnoreCondition.WhenWritingDefault;
      var tsType = ToTsType(type, prop, knownNames);

      sb.AppendLine($"  {propName}{(isOptional ? "?" : "")}: {(isNullable ? $"{tsType} | null" : tsType)};");
    }

    sb.AppendLine("}");
    sb.AppendLine();
  }

  private static Type? FindNearestExportedBase(Type type, HashSet<Type> interfaceTypeSet)
  {
    for (var current = type.BaseType; current != null && current != typeof(object) && current != typeof(ValueType); current = current.BaseType)
    {
      if (interfaceTypeSet.Contains(current))
      {
        return current;
      }
    }

    return null;
  }

  private static List<PropertyInfo> CollectPropertiesSinceExportedBase(Type type, Type? exportedBase)
  {
    var hierarchy = new List<Type>();
    for (var current = type; current != null && current != typeof(object) && current != typeof(ValueType) && current != exportedBase; current = current.BaseType)
    {
      hierarchy.Add(current);
    }

    // Walk from base-most down to derived so base properties keep canonical order while derived overrides win
    hierarchy.Reverse();
    var byName = new Dictionary<string, int>(StringComparer.Ordinal);
    var result = new List<PropertyInfo>();
    foreach (var level in hierarchy)
    {
      foreach (var prop in level.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
      {
        if (prop.GetIndexParameters().Length > 0)
        {
          continue;
        }

        if (byName.TryGetValue(prop.Name, out var idx))
        {
          result[idx] = prop;
        }
        else
        {
          byName[prop.Name] = result.Count;
          result.Add(prop);
        }
      }
    }

    return result;
  }

  private static bool TryResolvePolymorphicDiscriminator(Type type, out string propName, out string literal)
  {
    for (var current = type.BaseType; current != null && current != typeof(object); current = current.BaseType)
    {
      var match = current.GetCustomAttributes<JsonDerivedTypeAttribute>().FirstOrDefault(a => a.DerivedType == type);
      if (match != null)
      {
        propName = current.GetCustomAttribute<JsonPolymorphicAttribute>()?.TypeDiscriminatorPropertyName ?? "$type";
        literal = match.TypeDiscriminator switch
        {
          string s => $"'{s}'",
          int i => i.ToString(CultureInfo.InvariantCulture),
          _ => $"'{type.Name}'"
        };
        return true;
      }
    }

    foreach (var iface in type.GetInterfaces())
    {
      var match = iface.GetCustomAttributes<JsonDerivedTypeAttribute>().FirstOrDefault(a => a.DerivedType == type);
      if (match != null)
      {
        propName = iface.GetCustomAttribute<JsonPolymorphicAttribute>()?.TypeDiscriminatorPropertyName ?? "$type";
        literal = match.TypeDiscriminator switch
        {
          string s => $"'{s}'",
          int i => i.ToString(CultureInfo.InvariantCulture),
          _ => $"'{type.Name}'"
        };
        return true;
      }
    }

    propName = string.Empty;
    literal = string.Empty;
    return false;
  }

  private static void ExportSlotInterfaces(StringBuilder sb, List<Type> types)
  {
    ExportSlotMap(sb, "PanelKinds", types.Where(static t => typeof(PanelModel).IsAssignableFrom(t) && !t.IsAbstract));
    sb.AppendLine("export type PanelModel = PanelKinds[keyof PanelKinds];");
    sb.AppendLine();

    ExportSlotMap(sb, "CellKinds", types.Where(static t => typeof(CellModel).IsAssignableFrom(t) && !t.IsAbstract));
    sb.AppendLine("export type CellModel = CellKinds[keyof CellKinds];");
    sb.AppendLine();

    ExportSlotMap(sb, "HeaderKinds", types.Where(static t => typeof(HeaderModel).IsAssignableFrom(t) && !t.IsAbstract));
    sb.AppendLine("export type HeaderModel = HeaderKinds[keyof HeaderKinds];");
    sb.AppendLine();

    ExportSlotMap(sb, "FormElementKinds", types.Where(static t => typeof(FormElementModel).IsAssignableFrom(t) && !t.IsAbstract));
    sb.AppendLine("export type FormElementModel = FormElementKinds[keyof FormElementKinds];");
    sb.AppendLine();

    ExportSlotMap(sb, "NavElementKinds", types.Where(static t => typeof(NavElementModel).IsAssignableFrom(t) && !t.IsAbstract));
    sb.AppendLine("export type NavElementModel = NavElementKinds[keyof NavElementKinds];");
    sb.AppendLine();

    sb.AppendLine("export type PlatformKind =");
    sb.AppendLine("  | keyof PanelKinds");
    sb.AppendLine("  | keyof CellKinds");
    sb.AppendLine("  | keyof HeaderKinds");
    sb.AppendLine("  | keyof FormElementKinds");
    sb.AppendLine("  | keyof NavElementKinds;");
    sb.AppendLine();
  }

  private static void ExportSlotMap(StringBuilder sb, string interfaceName, IEnumerable<Type> unionTypes)
  {
    sb.AppendLine($"export interface {interfaceName} {{");
    foreach (var type in unionTypes.OrderBy(static t => t.Name, StringComparer.Ordinal))
    {
      var kind = type.Name.EndsWith("Model", StringComparison.Ordinal) ? type.Name[..^5] : type.Name;
      sb.AppendLine($"  {kind}: {type.Name};");
    }

    sb.AppendLine("}");
    sb.AppendLine();
  }

  private static string ToTsType(Type ownerType, PropertyInfo prop, HashSet<string> knownNames)
  {
    if (prop.DeclaringType == typeof(NavButtonModel) && prop.Name == nameof(NavButtonModel.Badge))
    {
      return "string | number";
    }

    var memberContext = $"Contract property '{ownerType.FullName}.{prop.Name}'";
    var oneOf = prop.GetCustomAttribute<OneOfAttribute>();
    if (oneOf?.Vocabularies.Count > 0)
    {
      foreach (var vocab in oneOf.Vocabularies)
      {
        if (!knownNames.Contains(vocab.Name))
        {
          throw new InvalidOperationException(
            $"{memberContext} [OneOf] references vocabulary '{vocab.FullName}' which is not marked with [UiContract].");
        }
      }

      var unionTs = string.Join(" | ", oneOf.Vocabularies.Select(static v => v.Name));
      var underlying = Nullable.GetUnderlyingType(prop.PropertyType) ?? prop.PropertyType;
      if (underlying.IsArray)
      {
        return unionTs.Contains(" | ", StringComparison.Ordinal) ? $"({unionTs})[]" : $"{unionTs}[]";
      }

      if (underlying.IsGenericType)
      {
        var genericDef = underlying.GetGenericTypeDefinition();
        if (genericDef == typeof(Dictionary<,>) ||
            genericDef == typeof(IDictionary<,>) ||
            genericDef == typeof(IReadOnlyDictionary<,>))
        {
          var keyType = MapType(underlying.GetGenericArguments()[0], memberContext, knownNames);
          return $"Record<{keyType}, {unionTs}>";
        }

        if (genericDef == typeof(List<>) ||
            genericDef == typeof(IList<>) ||
            genericDef == typeof(IReadOnlyList<>) ||
            genericDef == typeof(IEnumerable<>) ||
            genericDef == typeof(ICollection<>) ||
            genericDef == typeof(IReadOnlyCollection<>) ||
            genericDef == typeof(HashSet<>) ||
            genericDef == typeof(ISet<>) ||
            genericDef == typeof(IReadOnlySet<>))
        {
          return unionTs.Contains(" | ", StringComparison.Ordinal) ? $"({unionTs})[]" : $"{unionTs}[]";
        }
      }

      return unionTs;
    }

    return MapType(prop.PropertyType, memberContext, knownNames);
  }

  private static string MapType(Type type, string memberContext, HashSet<string> knownNames)
  {
    var underlying = Nullable.GetUnderlyingType(type) ?? type;

    if (underlying == typeof(string) || underlying == typeof(char) || underlying == typeof(Guid))
    {
      return "string";
    }

    if (underlying == typeof(bool))
    {
      return "boolean";
    }

    if (underlying == typeof(byte) || underlying == typeof(sbyte) ||
        underlying == typeof(short) || underlying == typeof(ushort) ||
        underlying == typeof(int) || underlying == typeof(uint) ||
        underlying == typeof(long) || underlying == typeof(ulong) ||
        underlying == typeof(float) || underlying == typeof(double) ||
        underlying == typeof(decimal))
    {
      return "number";
    }

    if (underlying == typeof(DateTime) || underlying == typeof(DateTimeOffset) ||
        underlying == typeof(DateOnly) || underlying == typeof(TimeOnly) || underlying == typeof(TimeSpan))
    {
      return "string";
    }

    if (underlying == typeof(object) || underlying == typeof(JsonElement))
    {
      return "unknown";
    }

    if (underlying.IsArray)
    {
      var elemTs = MapType(underlying.GetElementType()!, memberContext, knownNames);
      return elemTs.Contains(" | ", StringComparison.Ordinal) ? $"({elemTs})[]" : $"{elemTs}[]";
    }

    if (underlying.IsGenericType)
    {
      var genericDef = underlying.GetGenericTypeDefinition();
      if (genericDef == typeof(Dictionary<,>) ||
          genericDef == typeof(IDictionary<,>) ||
          genericDef == typeof(IReadOnlyDictionary<,>))
      {
        var keyType = MapType(underlying.GetGenericArguments()[0], memberContext, knownNames);
        var valType = MapType(underlying.GetGenericArguments()[1], memberContext, knownNames);
        return $"Record<{keyType}, {valType}>";
      }

      if (genericDef == typeof(List<>) ||
          genericDef == typeof(IList<>) ||
          genericDef == typeof(IReadOnlyList<>) ||
          genericDef == typeof(IEnumerable<>) ||
          genericDef == typeof(ICollection<>) ||
          genericDef == typeof(IReadOnlyCollection<>) ||
          genericDef == typeof(HashSet<>) ||
          genericDef == typeof(ISet<>) ||
          genericDef == typeof(IReadOnlySet<>))
      {
        var elemTs = MapType(underlying.GetGenericArguments()[0], memberContext, knownNames);
        return elemTs.Contains(" | ", StringComparison.Ordinal) ? $"({elemTs})[]" : $"{elemTs}[]";
      }
    }

    if (knownNames.Contains(underlying.Name))
    {
      return underlying.Name;
    }

    throw new InvalidOperationException(
      $"{memberContext} references unsupported or unmarked type '{underlying.FullName}'. Decorate contract types with [UiContract].");
  }
}
